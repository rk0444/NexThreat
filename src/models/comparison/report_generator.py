def run_pipeline() -> Dict[str, Any]:
    """Execute the full Phase 4.5 evaluation and serialization pipeline."""
    COMPARISON_REPORT_DIR.mkdir(parents=True, exist_ok=True)

    # 1. Timeline Synchronization
    synchronizer = MasterTimelineSynchronizer()
    sync_data = synchronizer.synchronize_timeline()

    # 2. Consistency Analysis
    consistency_data = analyze_consistency(sync_data)

    # 3. Cross-Model Evaluation
    cross_eval_data = evaluate_cross_model(
        sync_data,
        consistency_data["scope_a_pairwise_consistency"],
    )

    # 4. Threat Matrix & Dwell Times
    threat_matrix_data = evaluate_threat_matrix(sync_data)

    # 5. Lead-Time Analysis
    lead_time_data = analyze_lead_time(sync_data)

    # 6. Unified Inference Spec
    unified_spec_data = generate_unified_inference_spec(
        sync_data["ae_threshold"],
        sync_data["lstm_threshold"],
    )

    # 7. Summary Markdown
    summary_md = generate_phase_4_5_summary_markdown(
        cross_eval_data,
        consistency_data,
        threat_matrix_data,
        lead_time_data,
    )

    # Save deliverables
    save_json(cross_eval_data, CROSS_MODEL_EVALUATION_REPORT_PATH)
    save_json(consistency_data, MODEL_CONSISTENCY_REPORT_PATH)
    save_json(threat_matrix_data, TRI_MODEL_THREAT_MATRIX_PATH)
    save_json(lead_time_data, TEMPORAL_LEAD_TIME_REPORT_PATH)
    save_json(unified_spec_data, UNIFIED_INFERENCE_SPEC_PATH)
    PHASE_4_5_SUMMARY_MD_PATH.write_text(summary_md, encoding="utf-8")

    return {
        "cross_model_evaluation": cross_eval_data,
        "model_consistency": consistency_data,
        "tri_model_threat_matrix": threat_matrix_data,
        "temporal_lead_time": lead_time_data,
        "unified_inference_spec": unified_spec_data,
    }


if __name__ == "__main__":
    results = run_pipeline()
    print("Phase 4.5 pipeline execution completed successfully.")
    print("Deliverables generated in data/model_reports/comparison/.")
